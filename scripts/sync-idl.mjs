#!/usr/bin/env node
// Copies the IDL `anchor build` wrote in the program's checkout (XSOLANA_PROGRAM_DIR:
// target/idl/loot.json) into the JS client, as JSON and as an ES module (so a browser page without a bundler can
// import it). `--check` exits 1 when the committed copy differs from the build.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
if (!process.env.XSOLANA_PROGRAM_DIR) {
  console.error('Set XSOLANA_PROGRAM_DIR to a build of the loot program (its target/idl/loot.json).');
  process.exit(1);
}
const program = path.resolve(process.env.XSOLANA_PROGRAM_DIR);
const built = path.join(program, 'target/idl/loot.json');
const json = path.join(root, 'js/client/idl/loot.json');
const mjs = path.join(root, 'js/client/idl/loot.js');

const idl = JSON.parse(await readFile(built, 'utf8'));
const text = `${JSON.stringify(idl, null, 2)}\n`;
const module = `// Generated by scripts/sync-idl.mjs from target/idl/loot.json. Do not edit.\nexport default ${JSON.stringify(idl)};\n`;

if (process.argv.includes('--check')) {
  const [a, b] = await Promise.all([readFile(json, 'utf8').catch(() => ''), readFile(mjs, 'utf8').catch(() => '')]);
  if (a !== text || b !== module) {
    console.error('js/client/idl is out of date: run `node scripts/sync-idl.mjs` after `anchor build`.');
    process.exit(1);
  }
  console.log(`js/client/idl matches the build (loot ${idl.metadata.version}, ${idl.instructions.length} instructions).`);
} else {
  await writeFile(json, text);
  await writeFile(mjs, module);
  console.log(`wrote js/client/idl (loot ${idl.metadata.version}, ${idl.instructions.length} instructions)`);
}
